# Sessions
# ---------------------------------------------------------------------------
def list_sessions(paths: Paths, block: str | None = None) -> list[str]:
    """Session ids found in <data>/raw, optionally only one block (A-G)."""
    out = []
    for js in sorted(paths.raw.glob("*.json")):
        if not (js.with_suffix(".csv")).exists():
            continue
        meta = json.loads(js.read_text())
        if block is None or meta.get("block") == block:
            out.append(js.stem)
    return out


def load_meta(paths: Paths, session_id: str) -> dict:
    return json.loads((paths.raw / f"{session_id}.json").read_text())


def load_session(paths: Paths, session_id: str) -> tuple[pd.DataFrame, dict]:
    """Read one session: the CSV rows and the JSON sidecar.

    Adds two helper columns:
      t_s       time in seconds from the first row
      has_meas  True where faulted_mm holds a usable measurement
    """
    # round_trip: parse every number to exactly the double the firmware used
    # (pandas' default fast parser can be off in the last bit).
    df = pd.read_csv(paths.raw / f"{session_id}.csv", float_precision="round_trip")
    meta = load_meta(paths, session_id)
    df["t_s"] = (df["t_us"] - df["t_us"].iloc[0]) / 1e6
    if "faulted_mm" in df:
        df["has_meas"] = df["faulted_mm"] >= 0
    return df, meta


def load_splits(paths: Paths) -> dict:
    """{"train": [...], "validation": [...], "test": [...]} (see analysis/make_splits.py)."""
    if not paths.splits.exists():
        raise SystemExit(f"{paths.splits} not found. Run: python analysis/make_splits.py --data {paths.data}")
    return json.loads(paths.splits.read_text())


def sessions_in(paths: Paths, split: str, blocks: str | list[str]) -> list[str]:
    """Sessions that are in one split ("train"/"validation"/"test") and in the given blocks."""
    splits = load_splits(paths)
    want = set(blocks)
    out = []
    for sid in splits.get(split, []):
        js = paths.raw / f"{sid}.json"
        if js.exists() and json.loads(js.read_text()).get("block") in want:
            out.append(sid)
    return out


def load_truth(paths: Paths, session_id: str) -> pd.DataFrame:
    """Ground truth written by ground_truth.py (one row per CSV row)."""
    p = paths.processed / "truth" / f"{session_id}_truth.csv"
    if not p.exists():
        raise SystemExit(f"{p} not found. Run: python analysis/ground_truth.py --data {paths.data}")
    return pd.read_csv(p)


def write_json(path: Path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, default=_json_default) + "\n")


def _json_default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    raise TypeError(type(o))


def provenance(paths: Paths, sessions: list[str]) -> dict:
    """What every results file records about where it came from."""
    metas = [load_meta(paths, s) for s in sessions]
    return {
        "analysis_git_commit": git_commit(),
        "firmware_commits": sorted({m.get("firmware", {}).get("fw_commit", "unknown") for m in metas}),
        "sessions": sessions,
        "synthetic": any(m.get("synthetic", False) for m in metas),
    }
