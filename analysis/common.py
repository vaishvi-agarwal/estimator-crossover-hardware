"""Shared helpers for every analysis script: folders, loading sessions, safety checks.

Folder layout (SPEC.md section 7). Every script takes --data and --results so
the same code can run on the real data (the defaults) or on the synthetic
demo data in analysis/demo/:

    <data>/raw/<session_id>.csv        one row per sample (see data/README.md)
    <data>/raw/<session_id>.json       metadata sidecar written by logger.py
    <data>/processed/                  generated: truth, estimates
    <data>/splits.json                 train / validation / test sessions
    <results>/figures/, <results>/tables/   generated by the scripts
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parent.parent
DEFAULT_DATA = REPO / "data"
DEFAULT_RESULTS = REPO / "results"

# The blocks of the experiment protocol (SPEC.md section 5).
BLOCKS = {
    "A": "static noise",
    "B": "clean motion",
    "C": "variance bursts",
    "D": "frozen bursts",
    "E": "physical faults",
    "F": "measured-parameter bursts",
    "G": "integrated live run",
}

# Codes in the recovery_event column. They are the same numbers as the Spec 2
# guard's EventType (lib/sel_guard/src/guard_types.h), so one labelling rule
# works for both firmware builds.
EVENT_NONE = 0
EVENT_SEL_TRIP = 1
EVENT_SEL_LOCKOUT = 2
EVENT_SENSOR_FAULT = 3
EVENT_LADDER_STEP = 4
EVENT_SENSOR_RECOVERED = 5
EVENT_SENSOR_FAILED = 6
EVENT_CURRENT_SENSOR_ERROR = 7

MISSING = -1  # value of raw_mm / clean_mm / faulted_mm when there was no usable reading


def git_commit() -> str:
    """Short commit hash of this repository (with -dirty if files changed)."""
    try:
        rev = subprocess.check_output(["git", "rev-parse", "--short=10", "HEAD"], cwd=REPO, text=True,
                                      stderr=subprocess.DEVNULL).strip()
        dirty = subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=no"], cwd=REPO,
                                        text=True, stderr=subprocess.DEVNULL).strip()
        return rev + ("-dirty" if dirty else "")
    except Exception:
        return "unknown"


# ---------------------------------------------------------------------------
# Folders
# ---------------------------------------------------------------------------
class Paths:
    """All folders a script reads from or writes to."""

    def __init__(self, data: Path | str = DEFAULT_DATA, results: Path | str = DEFAULT_RESULTS):
        self.data = Path(data).resolve()
        self.results = Path(results).resolve()
        self.raw = self.data / "raw"
        self.processed = self.data / "processed"
        self.splits = self.data / "splits.json"
        self.figures = self.results / "figures"
        self.tables = self.results / "tables"

    def make_output_dirs(self):
        for p in (self.processed, self.figures, self.tables):
            p.mkdir(parents=True, exist_ok=True)


def add_path_args(parser):
    """Add the standard --data / --results options to an argparse parser."""
    parser.add_argument("--data", default=str(DEFAULT_DATA), help="data folder (default: data/)")
    parser.add_argument("--results", default=str(DEFAULT_RESULTS), help="results folder (default: results/)")
    return parser


def is_real_results_dir(results: Path) -> bool:
    return Path(results).resolve() == DEFAULT_RESULTS.resolve()


def check_no_synthetic_in_results(paths: Paths, metas: list[dict]):
    """Refuse to write anything made from synthetic data into the real results/ folder.

    SPEC.md section 9, rule 4: synthetic data may only be used in tests/ and analysis/demo/,
    never in results/.
    """
    if not is_real_results_dir(paths.results):
        return
    bad = [m.get("session_id", "?") for m in metas if m.get("synthetic", False)]
    if bad:
        raise SystemExit(
            f"Refusing to write to {paths.results}: sessions {bad[:5]} are marked synthetic. "
            "Synthetic data may only be analysed with --results analysis/demo/output."
        )


